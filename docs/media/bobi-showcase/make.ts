#!/usr/bin/env bun
// Builds the Bobi showcase video (the feature tour, extended with phase 8 and a live demo): narration → timeline →
// frame-exact recording of tour.html → H.264 video, the live clips from record-live.ts placed into their windows,
// voice + generated background music (ducked under the voice), subtitles (SRT/VTT and an MP4 subtitle track). Needs ffmpeg/ffprobe (Homebrew), Playwright's Chromium and a voice:
//   Piper (recommended, freely licensed): PIPER_BIN=<…/piper> PIPER_MODEL=<…/de_DE-thorsten-high.onnx>
//     [ESPEAK_DATA_PATH=<espeak-ng-data>] – voice model MIT, Thorsten-Voice data CC0
//   otherwise macOS `say -v Anna` (Apple licence: personal, non-commercial use only – drafts)
//   bun docs/media/bobi-showcase/record-live.ts     first: record the live clips (needs the local demo)
//   bun docs/media/bobi-showcase/make.ts            full build → bobi-showcase.mp4
//   bun docs/media/bobi-showcase/make.ts --timing   only narration + tour-data.js (for previewing tour.html)
//   bun docs/media/bobi-showcase/make.ts --stills   timeline + one PNG per scene for review
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import path from "node:path"
import { chromium } from "../../../packages/browser/node_modules/playwright-core/index.js"

const DIR = import.meta.dir
const WORK = path.join(DIR, ".work")
const FPS = 30
const PIPER = process.env.PIPER_BIN && process.env.PIPER_MODEL ? { bin: process.env.PIPER_BIN, model: process.env.PIPER_MODEL } : undefined
const LEAD = 0.5 // seconds before the narration starts in a scene
const TAIL = 1.1 // seconds after it ends
const MIN_SCENE = 4.5
const CLIP_IN = 0.6 // seconds into a scene before its live clip starts
const CLIP_RECT = { x: 400, y: 161, w: 1120, h: 630 } // inside the window drawn by tour.html, clear of the subtitles
const LIVE = path.join(DIR, ".work", "live")

/**
 * `text` is shown as subtitle; `speak` (optional) is what the voice says, e.g. "M C P" for "MCP"; `clip` (optional) is a
 * live clip from record-live.ts shown in the scene's window (the scene lasts at least as long as the clip).
 */
type Scene = { id: string; text: string; speak?: string; clip?: string }
const narration = JSON.parse(readFileSync(path.join(DIR, "narration.json"), "utf8")) as Scene[]
mkdirSync(WORK, { recursive: true })

const run = (cmd: string[]) => {
  const r = Bun.spawnSync(cmd, { stdout: "pipe", stderr: "pipe" })
  if (r.exitCode !== 0) throw new Error(`${cmd[0]} failed: ${r.stderr.toString().slice(-800)}`)
  return r.stdout.toString()
}
const duration = (file: string) => Number(run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", file]).trim())

// 1. Narration per scene.
let start = 0
const timeline = narration.map((scene) => {
  const spoken = scene.speak ?? scene.text
  const file = path.join(WORK, `${scene.id}.${PIPER ? "wav" : "aiff"}`)
  if (PIPER) {
    const r = Bun.spawnSync([PIPER.bin, "-m", PIPER.model, "-f", file, "--sentence-silence", "0.28", "--length-scale", "0.9", "--noise-scale", "0.7"], { stdin: Buffer.from(spoken), stdout: "pipe", stderr: "pipe" })
    if (r.exitCode !== 0) throw new Error(`piper failed: ${r.stderr.toString().slice(-500)}`)
  } else run(["say", "-v", "Anna", "-r", "178", "-o", file, spoken])
  const audioDur = duration(file)
  const clip = scene.clip ? path.join(LIVE, `${scene.clip}.mp4`) : undefined
  const clipDur = clip ? duration(clip) : 0
  const dur = Math.max(MIN_SCENE, LEAD + audioDur + TAIL, clip ? CLIP_IN + clipDur + 0.9 : 0)
  const entry = { id: scene.id, text: scene.text, start: Number(start.toFixed(3)), dur: Number(dur.toFixed(3)), audioStart: LEAD, audioDur: Number(audioDur.toFixed(3)), file, clip }
  start += dur
  return entry
})
const total = start
writeFileSync(path.join(DIR, "tour-data.js"), `// Generated by make.ts – narration timing per scene.\nwindow.TOUR = ${JSON.stringify({ scenes: timeline.map(({ file: _f, clip: _c, ...s }) => s) }, null, 1)}\n`)
console.error(`timeline: ${timeline.length} scenes, ${total.toFixed(1)} s, voice: ${PIPER ? "Piper" : "macOS say (draft licence)"}`)

// 2. Subtitles (sentence by sentence, timed by length – the same rule tour.html uses for the burned-in subtitles).
const stamp = (t: number, sep: string) => {
  const ms = Math.round(t * 1000)
  const h = Math.floor(ms / 3_600_000)
  const m = Math.floor((ms % 3_600_000) / 60_000)
  const s = Math.floor((ms % 60_000) / 1000)
  return `${String(h).padStart(2, "0")}:${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")}${sep}${String(ms % 1000).padStart(3, "0")}`
}
const cues = timeline.flatMap((s) => {
  const sentences = s.text.match(/[^.!?]+[.!?]*/g)!.map((x) => x.trim()).filter(Boolean)
  const chars = sentences.reduce((n, x) => n + x.length, 0)
  let at = s.start + s.audioStart
  return sentences.map((text) => {
    const d = (text.length / chars) * s.audioDur
    const cue = { from: at, to: at + d + 0.25, text }
    at += d
    return cue
  })
})
writeFileSync(path.join(DIR, "bobi-showcase.srt"), cues.map((c, i) => `${i + 1}\n${stamp(c.from, ",")} --> ${stamp(c.to, ",")}\n${c.text}\n`).join("\n"))
writeFileSync(path.join(DIR, "bobi-showcase.vtt"), `WEBVTT\n\n${cues.map((c) => `${stamp(c.from, ".")} --> ${stamp(c.to, ".")}\n${c.text}\n`).join("\n")}`)

// 3. Audio: voice track, generated music bed, ducking.
const voice = path.join(WORK, "voice.wav")
const inputs = timeline.flatMap((s) => ["-i", s.file])
const delays = timeline.map((s, i) => `[${i}:a]aresample=48000,adelay=${Math.round((s.start + s.audioStart) * 1000)}:all=1[v${i}]`).join(";")
run(["ffmpeg", "-y", "-loglevel", "error", ...inputs, "-filter_complex", `${delays};${timeline.map((_, i) => `[v${i}]`).join("")}amix=inputs=${timeline.length}:normalize=0,apad=whole_dur=${total.toFixed(3)}[out]`, "-map", "[out]", "-ac", "2", "-ar", "48000", voice])

// Music: a slow I–vi–IV–V progression of soft sine pads (A, F#m, D, E), generated here – no third-party audio.
const chords = [[110, 220, 277.18, 329.63], [92.5, 185, 220, 277.18], [73.42, 146.83, 220, 293.66], [82.41, 164.81, 207.65, 246.94]]
const bar = 6
const pad = (f: number[]) => `0.05*(${f.map((x) => `sin(2*PI*${x}*t)+0.3*sin(2*PI*${x * 2.003}*t)`).join("+")})*(0.75+0.25*sin(2*PI*0.25*t))`
const music = path.join(WORK, "music.wav")
const chordFiles = chords.map((f, i) => {
  const file = path.join(WORK, `chord${i}.wav`)
  run(["ffmpeg", "-y", "-loglevel", "error", "-f", "lavfi", "-i", `aevalsrc=${pad(f)}:s=48000:d=${bar + 1}`, "-af", "afade=t=in:d=1,afade=t=out:st=" + bar + ":d=1", "-ac", "2", file])
  return file
})
const loops = Math.ceil(total / (bar * chords.length)) + 1
const list = path.join(WORK, "chords.txt")
writeFileSync(list, Array.from({ length: loops }, () => chordFiles.map((f) => `file '${f}'\noutpoint ${bar}`).join("\n")).join("\n"))
run(["ffmpeg", "-y", "-loglevel", "error", "-f", "concat", "-safe", "0", "-i", list, "-af", `lowpass=f=1800,aecho=0.8:0.7:120|240:0.25|0.18,atrim=0:${total.toFixed(3)},afade=t=in:d=2,afade=t=out:st=${(total - 3).toFixed(3)}:d=3,volume=0.55`, "-ar", "48000", "-ac", "2", music])
const mix = path.join(DIR, "bobi-showcase.m4a")
run(["ffmpeg", "-y", "-loglevel", "error", "-i", voice, "-i", music, "-filter_complex",
  "[0:a]highpass=f=70,acompressor=threshold=-20dB:ratio=2.5:attack=8:release=150,asplit=2[vo][sc];[1:a][sc]sidechaincompress=threshold=0.02:ratio=8:attack=20:release=400[bed];[vo][bed]amix=inputs=2:normalize=0,loudnorm=I=-16:TP=-1.5:LRA=11,alimiter=limit=0.9[a]",
  "-map", "[a]", "-c:a", "aac", "-b:a", "192k", mix])
console.error(`audio: ${mix}`)

if (process.argv.includes("--timing")) process.exit(0)

// 4. Video: frame-exact rendering of tour.html.
const browser = await chromium.launch()
const tab = await browser.newPage({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 1 })
await tab.goto(`file://${path.join(DIR, "tour.html")}#record`)
await tab.evaluate(() => document.fonts.ready)
const seek = (t: number) => tab.evaluate((time) => (window as unknown as { __seek(t: number): void }).__seek(time), t)

if (process.argv.includes("--stills")) {
  const out = path.join(DIR, ".stills")
  rmSync(out, { recursive: true, force: true })
  mkdirSync(out)
  for (const s of timeline) {
    await seek(s.start + Math.min(s.dur - 0.6, 4.2))
    await tab.screenshot({ path: path.join(out, `${String(timeline.indexOf(s) + 1).padStart(2, "0")}-${s.id}.png`) })
  }
  await browser.close()
  console.error(`stills: ${out}`)
  process.exit(0)
}

const video = path.join(WORK, "video.mp4")
const encoder = Bun.spawn(["ffmpeg", "-y", "-loglevel", "error", "-f", "image2pipe", "-c:v", "mjpeg", "-framerate", String(FPS), "-i", "pipe:0", "-c:v", "libx264", "-preset", "slow", "-crf", "19", "-pix_fmt", "yuv420p", "-movflags", "+faststart", video], { stdin: "pipe" })
const frames = Math.ceil(total * FPS)
for (let frame = 0; frame < frames; frame++) {
  await seek(frame / FPS)
  encoder.stdin.write(await tab.screenshot({ type: "jpeg", quality: 93 }))
  if (frame % 600 === 0) console.error(`frame ${frame}/${frames}`)
}
encoder.stdin.end()
if ((await encoder.exited) !== 0) throw new Error("video encoding failed")
await browser.close()

// 5. The live clips go into their windows (overlay at the scene's time, held on the last picture to the scene's end).
const live = timeline.filter((s) => s.clip)
let picture = video
if (live.length) {
  picture = path.join(WORK, "video-live.mp4")
  const chain = live.map((s, i) => {
    const from = s.start + CLIP_IN
    const to = s.start + s.dur - 0.45
    return `[${i + 1}:v]scale=${CLIP_RECT.w}:${CLIP_RECT.h},tpad=stop_mode=clone:stop_duration=${(s.dur).toFixed(2)},setpts=PTS-STARTPTS+${from.toFixed(3)}/TB[c${i}];` +
      `[${i === 0 ? "0:v" : `b${i - 1}`}][c${i}]overlay=x=${CLIP_RECT.x}:y=${CLIP_RECT.y}:enable='between(t,${from.toFixed(3)},${to.toFixed(3)})':eof_action=pass[b${i}]`
  })
  run(["ffmpeg", "-y", "-loglevel", "error", "-i", video, ...live.flatMap((s) => ["-i", s.clip!]), "-filter_complex", chain.join(";"), "-map", `[b${live.length - 1}]`, "-c:v", "libx264", "-preset", "medium", "-crf", "19", "-pix_fmt", "yuv420p", "-movflags", "+faststart", picture])
  console.error(`live clips: ${live.map((s) => s.clip!.split("/").pop()).join(", ")}`)
}

// 6. Mux video, audio and the subtitle track.
const out = path.join(DIR, "bobi-showcase.mp4")
run(["ffmpeg", "-y", "-loglevel", "error", "-i", picture, "-i", mix, "-i", path.join(DIR, "bobi-showcase.srt"), "-map", "0:v", "-map", "1:a", "-map", "2:s", "-c:v", "copy", "-c:a", "copy", "-c:s", "mov_text", "-metadata:s:s:0", "language=deu", "-metadata:s:a:0", "language=deu", "-movflags", "+faststart", out])
console.error(`wrote ${out} (${total.toFixed(1)} s)`)
