#!/usr/bin/env bun
// Builds the Bobi feature tour: narration (macOS `say`, voice Anna) → timeline → frame-exact recording of
// tour.html → H.264 video, voice + generated background music (ducked under the voice), subtitles (SRT/VTT and
// an MP4 subtitle track). Needs macOS `say`, ffmpeg/ffprobe (Homebrew) and Playwright's Chromium.
//   bun docs/media/bobi-tour/make.ts            full build → bobi-tour.mp4
//   bun docs/media/bobi-tour/make.ts --timing   only narration + tour-data.js (for previewing tour.html)
//   bun docs/media/bobi-tour/make.ts --stills   timeline + one PNG per scene for review
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import path from "node:path"
import { chromium } from "../../../packages/browser/node_modules/playwright-core/index.js"

const DIR = import.meta.dir
const WORK = path.join(DIR, ".work")
const FPS = 30
const VOICE = "Anna"
const LEAD = 0.5 // seconds before the narration starts in a scene
const TAIL = 1.1 // seconds after it ends
const MIN_SCENE = 4.5

type Scene = { id: string; text: string }
const narration = JSON.parse(readFileSync(path.join(DIR, "narration.json"), "utf8")) as Scene[]
mkdirSync(WORK, { recursive: true })

const run = (cmd: string[]) => {
  const r = Bun.spawnSync(cmd, { stdout: "pipe", stderr: "pipe" })
  if (r.exitCode !== 0) throw new Error(`${cmd[0]} failed: ${r.stderr.toString().slice(-800)}`)
  return r.stdout.toString()
}
const duration = (file: string) => Number(run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", file]).trim())

// 1. Narration per scene.
let start = 0
const timeline = narration.map((scene) => {
  const file = path.join(WORK, `${scene.id}.aiff`)
  run(["say", "-v", VOICE, "-r", "178", "-o", file, scene.text])
  const audioDur = duration(file)
  const dur = Math.max(MIN_SCENE, LEAD + audioDur + TAIL)
  const entry = { id: scene.id, text: scene.text, start: Number(start.toFixed(3)), dur: Number(dur.toFixed(3)), audioStart: LEAD, audioDur: Number(audioDur.toFixed(3)), file }
  start += dur
  return entry
})
const total = start
writeFileSync(path.join(DIR, "tour-data.js"), `// Generated by make.ts – narration timing per scene.\nwindow.TOUR = ${JSON.stringify({ scenes: timeline.map(({ file: _f, ...s }) => s) }, null, 1)}\n`)
console.error(`timeline: ${timeline.length} scenes, ${total.toFixed(1)} s`)

// 2. Subtitles (sentence by sentence, timed by length – the same rule tour.html uses for the burned-in subtitles).
const stamp = (t: number, sep: string) => {
  const ms = Math.round(t * 1000)
  const h = Math.floor(ms / 3_600_000)
  const m = Math.floor((ms % 3_600_000) / 60_000)
  const s = Math.floor((ms % 60_000) / 1000)
  return `${String(h).padStart(2, "0")}:${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")}${sep}${String(ms % 1000).padStart(3, "0")}`
}
const cues = timeline.flatMap((s) => {
  const sentences = s.text.match(/[^.!?]+[.!?]*/g)!.map((x) => x.trim()).filter(Boolean)
  const chars = sentences.reduce((n, x) => n + x.length, 0)
  let at = s.start + s.audioStart
  return sentences.map((text) => {
    const d = (text.length / chars) * s.audioDur
    const cue = { from: at, to: at + d + 0.25, text }
    at += d
    return cue
  })
})
writeFileSync(path.join(DIR, "bobi-tour.srt"), cues.map((c, i) => `${i + 1}\n${stamp(c.from, ",")} --> ${stamp(c.to, ",")}\n${c.text}\n`).join("\n"))
writeFileSync(path.join(DIR, "bobi-tour.vtt"), `WEBVTT\n\n${cues.map((c) => `${stamp(c.from, ".")} --> ${stamp(c.to, ".")}\n${c.text}\n`).join("\n")}`)

// 3. Audio: voice track, generated music bed, ducking.
const voice = path.join(WORK, "voice.wav")
const inputs = timeline.flatMap((s) => ["-i", s.file])
const delays = timeline.map((s, i) => `[${i}:a]aresample=48000,adelay=${Math.round((s.start + s.audioStart) * 1000)}:all=1[v${i}]`).join(";")
run(["ffmpeg", "-y", "-loglevel", "error", ...inputs, "-filter_complex", `${delays};${timeline.map((_, i) => `[v${i}]`).join("")}amix=inputs=${timeline.length}:normalize=0,apad=whole_dur=${total.toFixed(3)}[out]`, "-map", "[out]", "-ac", "2", "-ar", "48000", voice])

// Music: a slow I–vi–IV–V progression of soft sine pads (A, F#m, D, E), generated here – no third-party audio.
const chords = [[110, 220, 277.18, 329.63], [92.5, 185, 220, 277.18], [73.42, 146.83, 220, 293.66], [82.41, 164.81, 207.65, 246.94]]
const bar = 6
const pad = (f: number[]) => `0.05*(${f.map((x) => `sin(2*PI*${x}*t)+0.3*sin(2*PI*${x * 2.003}*t)`).join("+")})*(0.75+0.25*sin(2*PI*0.25*t))`
const music = path.join(WORK, "music.wav")
const chordFiles = chords.map((f, i) => {
  const file = path.join(WORK, `chord${i}.wav`)
  run(["ffmpeg", "-y", "-loglevel", "error", "-f", "lavfi", "-i", `aevalsrc=${pad(f)}:s=48000:d=${bar + 1}`, "-af", "afade=t=in:d=1,afade=t=out:st=" + bar + ":d=1", "-ac", "2", file])
  return file
})
const loops = Math.ceil(total / (bar * chords.length)) + 1
const list = path.join(WORK, "chords.txt")
writeFileSync(list, Array.from({ length: loops }, () => chordFiles.map((f) => `file '${f}'\noutpoint ${bar}`).join("\n")).join("\n"))
run(["ffmpeg", "-y", "-loglevel", "error", "-f", "concat", "-safe", "0", "-i", list, "-af", `lowpass=f=1800,aecho=0.8:0.7:120|240:0.25|0.18,atrim=0:${total.toFixed(3)},afade=t=in:d=2,afade=t=out:st=${(total - 3).toFixed(3)}:d=3,volume=0.55`, "-ar", "48000", "-ac", "2", music])
const mix = path.join(DIR, "bobi-tour.m4a")
run(["ffmpeg", "-y", "-loglevel", "error", "-i", voice, "-i", music, "-filter_complex",
  "[0:a]asplit=2[vo][sc];[1:a][sc]sidechaincompress=threshold=0.02:ratio=8:attack=20:release=400[bed];[vo][bed]amix=inputs=2:normalize=0,alimiter=limit=0.95[a]",
  "-map", "[a]", "-c:a", "aac", "-b:a", "192k", mix])
console.error(`audio: ${mix}`)

if (process.argv.includes("--timing")) process.exit(0)

// 4. Video: frame-exact rendering of tour.html.
const browser = await chromium.launch()
const tab = await browser.newPage({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 1 })
await tab.goto(`file://${path.join(DIR, "tour.html")}#record`)
await tab.evaluate(() => document.fonts.ready)
const seek = (t: number) => tab.evaluate((time) => (window as unknown as { __seek(t: number): void }).__seek(time), t)

if (process.argv.includes("--stills")) {
  const out = path.join(DIR, ".stills")
  rmSync(out, { recursive: true, force: true })
  mkdirSync(out)
  for (const s of timeline) {
    await seek(s.start + Math.min(s.dur - 0.6, 4.2))
    await tab.screenshot({ path: path.join(out, `${String(timeline.indexOf(s) + 1).padStart(2, "0")}-${s.id}.png`) })
  }
  await browser.close()
  console.error(`stills: ${out}`)
  process.exit(0)
}

const video = path.join(WORK, "video.mp4")
const encoder = Bun.spawn(["ffmpeg", "-y", "-loglevel", "error", "-f", "image2pipe", "-c:v", "mjpeg", "-framerate", String(FPS), "-i", "pipe:0", "-c:v", "libx264", "-preset", "slow", "-crf", "19", "-pix_fmt", "yuv420p", "-movflags", "+faststart", video], { stdin: "pipe" })
const frames = Math.ceil(total * FPS)
for (let frame = 0; frame < frames; frame++) {
  await seek(frame / FPS)
  encoder.stdin.write(await tab.screenshot({ type: "jpeg", quality: 93 }))
  if (frame % 600 === 0) console.error(`frame ${frame}/${frames}`)
}
encoder.stdin.end()
if ((await encoder.exited) !== 0) throw new Error("video encoding failed")
await browser.close()

// 5. Mux video, audio and the subtitle track.
const out = path.join(DIR, "bobi-tour.mp4")
run(["ffmpeg", "-y", "-loglevel", "error", "-i", video, "-i", mix, "-i", path.join(DIR, "bobi-tour.srt"), "-map", "0:v", "-map", "1:a", "-map", "2:s", "-c:v", "copy", "-c:a", "copy", "-c:s", "mov_text", "-metadata:s:s:0", "language=deu", "-metadata:s:a:0", "language=deu", "-movflags", "+faststart", out])
console.error(`wrote ${out} (${total.toFixed(1)} s)`)
