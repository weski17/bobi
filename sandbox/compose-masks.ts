#!/usr/bin/env bun
// Writes a Docker Compose override that hides the project's .bobiignore'd files inside the server container
// (empty read-only mounts), like sandbox/bobi-sandbox.sh does for Podman. Compose loads compose.override.yaml
// automatically:   bun sandbox/compose-masks.ts "$BOBI_PROJECT" > compose.override.yaml
import { mkdirSync } from "node:fs"
import os from "node:os"
import path from "node:path"
import { ignoredPaths } from "../scripts/bobiignore-paths.ts"

export function composeMasks(project: string, empty: string): string {
  const paths = ignoredPaths(project)
  const volumes = paths.map((p) =>
    p.endsWith("/") ? `      - ${JSON.stringify(`${empty}:${p.slice(0, -1)}:ro`)}` : `      - ${JSON.stringify(`/dev/null:${p}:ro`)}`,
  )
  return [
    "# Generated by sandbox/compose-masks.ts – hides files excluded by .bobiignore inside the server container.",
    `# Project: ${project}`,
    "services:",
    "  server:",
    ...(volumes.length ? ["    volumes:", ...volumes] : ["    {}"]),
    "",
  ].join("\n")
}

if (import.meta.main) {
  const project = process.argv[2]
  if (!project) {
    console.error('usage: bun sandbox/compose-masks.ts <project> > compose.override.yaml')
    process.exit(2)
  }
  const empty = path.join(process.env.BOBI_HOME ?? path.join(os.homedir(), ".bobi"), "sandbox", "empty")
  mkdirSync(empty, { recursive: true })
  process.stdout.write(composeMasks(path.resolve(project), empty))
}
